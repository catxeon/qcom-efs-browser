struct sockaddr_qrtr {
    unsigned short sq_family;
    uint32_t sq_node;
    uint32_t sq_port;
};

struct qrtr_ctrl_pkt {
    uint32_t cmd;
    uint32_t service;
    uint32_t instance;
    uint32_t node;
    uint32_t port;
} __attribute__((packed));

/* The nameserver answers a NEW_LOOKUP with one NEW_SERVER per matching
 * service.  The first one with a real port wins, exactly as in the replay
 * tool.  0 on success. */
static int discover(uint32_t *node, uint32_t *port, char *err, size_t errsz)
{
    int fd = socket(AF_QIPCRTR, SOCK_DGRAM, 0);
    if (fd < 0) {
        snprintf(err, errsz, "socket(AF_QIPCRTR) failed: %s", strerror(errno));
        return -1;
    }

    struct timeval tv = { LOOKUP_TIMEOUT_MS / 1000, (LOOKUP_TIMEOUT_MS % 1000) * 1000 };
    if (setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof tv) < 0) {
        snprintf(err, errsz, "setsockopt failed: %s", strerror(errno));
        close(fd);
        return -1;
    }

    struct sockaddr_qrtr ctrl;
    memset(&ctrl, 0, sizeof ctrl);
    ctrl.sq_family = AF_QIPCRTR;
    ctrl.sq_node = 1;              /* QRTR_CTRL_NODE */
    ctrl.sq_port = QRTR_PORT_CTRL;

    struct qrtr_ctrl_pkt q;
    memset(&q, 0, sizeof q);
    q.cmd = QRTR_TYPE_NEW_LOOKUP;
    q.service = SSR_SERVICE;

    for (int t = 0; t < LOOKUP_TRIES; t++) {
        if (sendto(fd, &q, sizeof q, 0, (struct sockaddr *)&ctrl, sizeof ctrl) < 0) {
            snprintf(err, errsz, "QRTR lookup failed: %s", strerror(errno));
            close(fd);
            return -1;
        }

        for (;;) {
            struct qrtr_ctrl_pkt in;
            ssize_t n = recv(fd, &in, sizeof in, 0);
            if (n < 0) break;                        /* timeout -> next try */
            if (n != (ssize_t)sizeof in) continue;
            if (in.cmd != QRTR_TYPE_NEW_SERVER) continue;
            if (!in.service && !in.instance && !in.node && !in.port) break;
            if (in.service != SSR_SERVICE || !in.port) continue;
            *node = in.node;
            *port = in.port;
            close(fd);
            return 0;
        }
    }

    close(fd);
    snprintf(err, errsz,
             "no SSR service (0xFFE4) published on the QRTR bus - "
             "modem restart is only available on Xiaomi devices");
    return -1;
}

static int64_t now_ms(void)
{
    struct timeval tv;
    gettimeofday(&tv, NULL);
    return (int64_t)tv.tv_sec * 1000 + tv.tv_usec / 1000;
}

/* Sends one datagram and waits up to REPLY_TIMEOUT_MS for one with the request's
 * transaction id and message id echoed back.  0 on match, -1 on timeout. */
static int xfer(int fd, const struct sockaddr_qrtr *dst, socklen_t dstlen,
                char *err, size_t errsz)
{
    ssize_t w = (dst != NULL)
        ? sendto(fd, ssr_request, sizeof ssr_request, 0,
                 (const struct sockaddr *)dst, dstlen)
        : send(fd, ssr_request, sizeof ssr_request, 0);
    if (w != (ssize_t)sizeof ssr_request) {
        snprintf(err, errsz, "sending the SSR request failed: %s", strerror(errno));
        return -1;
    }

    int64_t deadline = now_ms() + REPLY_TIMEOUT_MS;

    for (;;) {
        int left = (int)(deadline - now_ms());
        if (left <= 0) {
            snprintf(err, errsz, "the SSR service did not answer");
            return -1;
        }

        struct pollfd p = { fd, POLLIN, 0 };
        int pr = poll(&p, 1, left);
        if (pr < 0) {
            if (errno == EINTR) continue;
            snprintf(err, errsz, "poll failed: %s", strerror(errno));
            return -1;
        }
        if (pr == 0) {
            snprintf(err, errsz, "the SSR service did not answer");
            return -1;
        }

        uint8_t rsp[1024];
        ssize_t n = recv(fd, rsp, sizeof rsp, 0);
        if (dst == NULL && n == 0) { snprintf(err, errsz, "the SSR endpoint closed the connection"); return -1; }
        if (n <= 0) continue;
        if (n < 5) continue;                     /* too short to hold the txn+msg_id echo */
        /* response type byte not gated — unverified for this proprietary service; the proven replay tool applies no flag test either. The txn+msg_id echo is the discriminator. */
        if (rsp[1] != ssr_request[1] || rsp[2] != ssr_request[2]) continue;
        if (rsp[3] != ssr_request[3] || rsp[4] != ssr_request[4]) continue;
        qlog("SSR: %zd-byte response, transaction matches", n);
        return 0;
    }
}

int ssr_trigger(char *err, size_t errsz)
{
    if (g_mock_path[0]) {
        /* Test rig: the mock serves the fake 0xFFE4 endpoint on <mock>.ssr. */
        char path[sizeof g_mock_path + 4];
        snprintf(path, sizeof path, "%s.ssr", g_mock_path);

        int fd = socket(AF_UNIX, SOCK_SEQPACKET, 0);
        if (fd < 0) {
            snprintf(err, errsz, "socket(AF_UNIX) failed: %s", strerror(errno));
            return -1;
        }
        struct sockaddr_un sa;
        memset(&sa, 0, sizeof sa);
        sa.sun_family = AF_UNIX;
        if (strlen(path) >= sizeof sa.sun_path) {
            snprintf(err, errsz, "socket path is too long");
            close(fd);
            return -1;
        }
        memcpy(sa.sun_path, path, strlen(path));
        if (connect(fd, (struct sockaddr *)&sa, sizeof sa) < 0) {
            snprintf(err, errsz, "connect %s: %s", path, strerror(errno));
            close(fd);
            return -1;
        }
        int rc = xfer(fd, NULL, 0, err, errsz);
        close(fd);
        return rc;
    }

    uint32_t node = 0, port = 0;
    if (discover(&node, &port, err, errsz) < 0) return -1;
    qlog("SSR: vendor service 0xFFE4 at node %u port %u", node, port);

    int fd = socket(AF_QIPCRTR, SOCK_DGRAM, 0);
    if (fd < 0) {
        snprintf(err, errsz, "socket(AF_QIPCRTR) failed: %s", strerror(errno));
        return -1;
    }

    struct sockaddr_qrtr dst;
    memset(&dst, 0, sizeof dst);
    dst.sq_family = AF_QIPCRTR;
    dst.sq_node = node;
    dst.sq_port = port;

    int rc = xfer(fd, &dst, sizeof dst, err, errsz);
    close(fd);
    return rc;
}
